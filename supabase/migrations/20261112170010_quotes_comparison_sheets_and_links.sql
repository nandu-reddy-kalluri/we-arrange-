-- 1. Link enquiries to assigned concierge/admin specialist
ALTER TABLE public.enquiries
  ADD COLUMN IF NOT EXISTS assigned_specialist_id uuid
    REFERENCES public.users (user_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_enquiries_assigned_specialist_id
  ON public.enquiries (assigned_specialist_id);

DROP POLICY IF EXISTS "Customers create own enquiries" ON public.enquiries;
CREATE POLICY "Customers create own enquiries"
  ON public.enquiries FOR INSERT TO authenticated
  WITH CHECK (
    (select auth.uid()) = user_id
    AND status = 'Pending'::public.status_enum
    AND assigned_specialist_id IS NULL
  );

-- 2. Link favorites to optional customer collections + prevent cross-user collection IDOR
ALTER TABLE public.favorites
  ADD COLUMN IF NOT EXISTS collection_id bigint
    REFERENCES public.collections (collection_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_favorites_collection_id
  ON public.favorites (collection_id);

GRANT UPDATE (collection_id) ON public.favorites TO authenticated;

DROP POLICY IF EXISTS "Customers manage own favorites" ON public.favorites;
CREATE POLICY "Customers manage own favorites"
  ON public.favorites FOR ALL TO authenticated
  USING ((select auth.uid()) = user_id)
  WITH CHECK (
    (select auth.uid()) = user_id
    AND (
      collection_id IS NULL
      OR EXISTS (
        SELECT 1
        FROM public.collections c
        WHERE c.collection_id = favorites.collection_id
          AND c.user_id = (select auth.uid())
      )
    )
  );

-- 3. Human-curated partner quotes (INR pricing, single venue OR vendor target)
CREATE TABLE IF NOT EXISTS public.quotes (
  quote_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_id bigint NOT NULL REFERENCES public.enquiries (enquiry_id) ON DELETE CASCADE,
  venue_id bigint REFERENCES public.venues (venue_id) ON DELETE SET NULL,
  vendor_id bigint REFERENCES public.vendors (vendor_id) ON DELETE SET NULL,
  collected_by uuid NOT NULL REFERENCES public.users (user_id) ON DELETE RESTRICT,
  package_name text NOT NULL,
  base_cost_inr numeric(12, 2) NOT NULL CHECK (base_cost_inr >= 0),
  currency text NOT NULL DEFAULT 'INR' CHECK (currency = 'INR'),
  catering_included boolean NOT NULL DEFAULT false,
  inclusions jsonb NOT NULL DEFAULT '[]'::jsonb,
  exclusions jsonb NOT NULL DEFAULT '[]'::jsonb,
  notes text,
  valid_until date,
  status public.status_enum NOT NULL DEFAULT 'Draft'::public.status_enum,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT quotes_single_partner_check CHECK (
    (CASE WHEN venue_id IS NOT NULL THEN 1 ELSE 0 END)
    + (CASE WHEN vendor_id IS NOT NULL THEN 1 ELSE 0 END) = 1
  )
);

CREATE INDEX IF NOT EXISTS idx_quotes_enquiry_id ON public.quotes (enquiry_id);
CREATE INDEX IF NOT EXISTS idx_quotes_venue_id ON public.quotes (venue_id);
CREATE INDEX IF NOT EXISTS idx_quotes_vendor_id ON public.quotes (vendor_id);
CREATE INDEX IF NOT EXISTS idx_quotes_collected_by ON public.quotes (collected_by);

DROP TRIGGER IF EXISTS set_updated_at ON public.quotes;
CREATE TRIGGER set_updated_at
  BEFORE UPDATE ON public.quotes
  FOR EACH ROW
  EXECUTE FUNCTION extensions.moddatetime('updated_at');

ALTER TABLE public.quotes ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.quotes FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.quotes TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.quotes_quote_id_seq TO service_role;
GRANT SELECT ON TABLE public.quotes TO authenticated;

DROP POLICY IF EXISTS "Customers view shared quotes for own enquiries" ON public.quotes;
CREATE POLICY "Customers view shared quotes for own enquiries"
  ON public.quotes FOR SELECT TO authenticated
  USING (
    status <> 'Draft'::public.status_enum
    AND EXISTS (
      SELECT 1
      FROM public.enquiries e
      WHERE e.enquiry_id = quotes.enquiry_id
        AND e.user_id = (select auth.uid())
    )
  );

DROP POLICY IF EXISTS "Concierge and admins view all quotes" ON public.quotes;
CREATE POLICY "Concierge and admins view all quotes"
  ON public.quotes FOR SELECT TO authenticated
  USING (private.is_concierge_or_admin());

-- 4. Concierge comparison sheets compiled from curated quotes
CREATE TABLE IF NOT EXISTS public.comparison_sheets (
  comparison_sheet_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_id bigint NOT NULL REFERENCES public.enquiries (enquiry_id) ON DELETE CASCADE,
  created_by uuid NOT NULL REFERENCES public.users (user_id) ON DELETE RESTRICT,
  title text NOT NULL,
  quote_ids bigint[] NOT NULL DEFAULT '{}'::bigint[],
  summary_notes text,
  status public.status_enum NOT NULL DEFAULT 'Draft'::public.status_enum,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

