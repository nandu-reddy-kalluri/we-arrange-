-- 4. Add target-exclusivity & duplicate-prevention integrity on favorites & reviews
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.favorites'::regclass
      AND conname = 'favorites_single_target_check'
  ) THEN
    ALTER TABLE public.favorites
      ADD CONSTRAINT favorites_single_target_check CHECK (
        (CASE WHEN venue_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN vendor_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN inspiration_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN blog_id IS NOT NULL THEN 1 ELSE 0 END) = 1
      );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.reviews'::regclass
      AND conname = 'reviews_single_target_check'
  ) THEN
    ALTER TABLE public.reviews
      ADD CONSTRAINT reviews_single_target_check CHECK (
        (CASE WHEN venue_id IS NOT NULL THEN 1 ELSE 0 END)
        + (CASE WHEN vendor_id IS NOT NULL THEN 1 ELSE 0 END) = 1
      );
  END IF;
END $$;

