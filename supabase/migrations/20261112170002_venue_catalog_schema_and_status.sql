-- 1. Ensure sequence & identity/default + service_role grant on venue_menus.menu_id
DO $$
DECLARE
  v_is_identity text;
  v_col_default text;
BEGIN
  SELECT is_identity, column_default
  INTO v_is_identity, v_col_default
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'venue_menus'
    AND column_name = 'menu_id';

  IF v_is_identity = 'NO' AND v_col_default IS NULL THEN
    CREATE SEQUENCE IF NOT EXISTS public.venue_menus_menu_id_seq
      OWNED BY public.venue_menus.menu_id;

    ALTER TABLE public.venue_menus
      ALTER COLUMN menu_id SET DEFAULT nextval('public.venue_menus_menu_id_seq'::regclass);
  END IF;
END $$;

GRANT USAGE, SELECT ON SEQUENCE public.venue_menus_menu_id_seq TO service_role;

SELECT setval(
  'public.venue_menus_menu_id_seq',
  COALESCE((SELECT MAX(menu_id) FROM public.venue_menus), 1),
  (SELECT COUNT(*) > 0 FROM public.venue_menus)
);

-- 2. Add venues.slug and populate deterministically from existing venue_name
ALTER TABLE public.venues
  ADD COLUMN IF NOT EXISTS slug text;

WITH normalized AS (
  SELECT
    venue_id,
    NULLIF(
      trim(BOTH '-' FROM regexp_replace(lower(trim(venue_name)), '[^a-z0-9]+', '-', 'g')),
      ''
    ) AS base_slug
  FROM public.venues
),
ranked AS (
  SELECT
    venue_id,
    COALESCE(base_slug, 'venue-' || venue_id::text) AS safe_base_slug,
    COUNT(*) OVER (PARTITION BY COALESCE(base_slug, 'venue-' || venue_id::text)) AS name_count
  FROM normalized
)
UPDATE public.venues v
SET slug = CASE
  WHEN r.name_count > 1 THEN r.safe_base_slug || '-' || r.venue_id::text
  ELSE r.safe_base_slug
END
FROM ranked r
WHERE v.venue_id = r.venue_id
  AND v.slug IS NULL;

ALTER TABLE public.venues
  ALTER COLUMN slug SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conrelid = 'public.venues'::regclass
      AND conname = 'venues_slug_key'
  ) THEN
    ALTER TABLE public.venues
      ADD CONSTRAINT venues_slug_key UNIQUE (slug);
  END IF;
END $$;

-- Grant SELECT on the newly created slug column to anon & authenticated
GRANT SELECT (slug) ON public.venues TO anon, authenticated;

